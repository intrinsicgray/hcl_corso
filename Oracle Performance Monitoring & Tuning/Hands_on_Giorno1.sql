--2.Fase 1: EXPLAIN PLAN e DBMS_XPLAN (La Previsione): Strumento 1.
--Iniziamo con una query semplice che cerca ordini specifici. 
--In questo modo non eseguiamo la query, ma chiedono al database come la eseguirebbe (Lanciare come script da DBeaver).

EXPLAIN PLAN FOR
SELECT * FROM ordini WHERE stato = 'IN_ATTESA' AND importo > 900;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY);

--Come si legge l'output:
--•	Operation (TABLE ACCESS FULL): Il database esplorerà tutte le 500.000 righe.
--•	Rows: Questa è la stima del CBO (es. 50.000 righe). Il CBO fa questa deduzione basandosi sulle statistiche (DBMS_STATS) raccolte in precedenza.
--•	Cost (%CPU): Il "prezzo" dell'operazione. Più è alto, più risorse serviranno. Questo è il numero che dobbiamo abbattere il Giorno 2 creando gli indici.


--3.Fase 2: Eseguire la query con l'hint (La Realtà): Strumento 2.
--EXPLAIN PLAN è solo una stima. 
--Aggiungere l'hint /*+ GATHER_PLAN_STATISTICS */ subito dopo la parola SELECT dice all'ottimizzatore: "Esegui la query per davvero, ma conta ogni singola riga letta, la RAM utilizzata e le letture su disco".
--Aggiungiungiamo un commento personalizzato (un "tag") dentro la query, insieme all'hint. Questo ci permetterà di rintracciarla facilmente in mezzo a migliaia di altre query.

SELECT /*+ GATHER_PLAN_STATISTICS LAB_TUNING_01 */ *
 FROM ordini WHERE stato = 'IN_ATTESA' AND importo > 900;

--Ora, invece di affidarci al caso, andiamo a cercare la nostra query nella V$SQL usando il tag appena inventato (escludendo la query di ricerca stessa).

SELECT sql_id, child_number, sql_text 
FROM v$sql 
WHERE sql_text LIKE '%LAB_TUNING_01%' 
AND sql_text NOT LIKE '%v$sql%'

--Ora inserisci l'ID esatto dentro la funzione DISPLAY_CURSOR. In questo modo aggiriamo qualsiasi interferenza del client grafico. (Sostituisci il primo parametro con il tuo vero SQL_ID, mantenendo gli apici).
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR('bt7rhy1h9721f', NULL, 'ALLSTATS LAST'));

--L'output generato sarà un piano di esecuzione molto più ricco di quello standard:
--•	E-Rows (Estimated Rows): Quante righe l'ottimizzatore pensava di trovare (la stima vista nella Fase 1).
--•	A-Rows (Actual Rows): Quante righe ha realmente trovato. Se E-Rows e A-Rows sono molto diverse, significa che le statistiche del DB sono vecchie e l'ottimizzatore sta prendendo decisioni sbagliate.
--•	Buffers (Logical Reads): Indica quanti blocchi di dati sono stati letti dalla memoria RAM (Buffer Cache).
--•	Reads (Physical Reads): I blocchi letti fisicamente dal disco.

--Se la colonna Reads non appare, significa semplicemente che le letture fisiche su disco sono state zero. 
--Oracle nasconde dinamicamente le colonne vuote per mantenere l'output compatto e leggibile.
--Perché le letture su disco sono state zero?
--Perché i dati che hai interrogato erano già presenti nella memoria RAM del database (la Buffer Cache). 
--Avendo tu appena creato la tabella, inserito i dati o fatto test precedenti, Oracle aveva i blocchi di dati "caldi" in memoria. 
--Ha soddisfatto la tua query leggendo solo dai Buffers (Logical Reads) senza dover toccare la lentezza del disco.


ALTER SYSTEM FLUSH BUFFER_CACHE;

--1.	Riesegui la query con l'hint /*+ GATHER_PLAN_STATISTICS ... */.
--2.	Estrai di nuovo il piano con il SQL_ID.
--il database ha dovuto fisicamente recuperare i blocchi dal disco per caricarli in RAM.

