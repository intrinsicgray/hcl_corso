--1.Fase 1: Generare il carico (La 'Killer Query'):Terminale 1.
--Questo script simula un'applicazione scritta male che genera un loop continuo causando un alto consumo di CPU e costringendo il database a fare letture continue.
CONNECT tuning_user/tuning_pwd@localhost:1521/XEPDB1;

-- Simula una sessione che consuma molta CPU e I/O
DECLARE
    v_dummy NUMBER;
BEGIN
    FOR i IN 1..100000 LOOP
        -- Full table scan ripetuto inutilmente
        SELECT COUNT(importo) INTO v_dummy FROM ordini WHERE stato = 'IN_ATTESA';
    END LOOP;
END;

--Nota: Questo terminale rimarrà "appeso" ed eseguirà il blocco in loop. È esattamente quello che vogliamo.
--2.Fase 2: Individuare le sessioni attive:Terminale 2.
--Dal secondo terminale (connesso come SYS o tuning_user).L'obiettivo è filtrare i processi di background e trovare chi sta effettivamente lavorando.

SELECT sid, serial#, username, status, machine, program, sql_id
FROM v$session
WHERE status = 'ACTIVE'
AND type != 'BACKGROUND'
AND username IS NOT NULL;

--Cosa notare:
--•	SID e SERIAL#: Sono le coordinate esatte della sessione (serviranno per le query successive o per "killare" il processo).
--•	SQL_ID: È la targa identificativa dell'istruzione SQL che quella sessione sta eseguendo in questo preciso millisecondo. Fai appuntare agli studenti questo valore.
--3.Fase 3: Misurare il consumo di CPU e Memoria:Terminale 2.
--Ora che hanno trovato il SID (es. 45), bisogna capire quante risorse si stanno utilizzando. 
--In Oracle, le metriche di consumo si trovano incrociando V$SESSTAT (i valori) con V$STATNAME (i nomi delle metriche).

SELECT s.sid, s.username, n.name AS metrica, st.value AS valore
FROM v$session s
JOIN v$sesstat st ON s.sid = st.sid
JOIN v$statname n ON st.statistic# = n.statistic#
WHERE s.status = 'ACTIVE'
AND s.type != 'BACKGROUND'
AND n.name IN ('CPU used by this session', 'session pga memory', 'physical reads')
ORDER BY s.sid, n.name;

--Cosa notare:
--•	CPU used by this session: Espressa in centesimi di secondo. Se rieseguono la query più volte, questo numero crescere rapidamente a causa del loop.
--•	session pga memory: Mostra la memoria privata (PGA) allocata dalla sessione in byte.
--•	physical reads: Mostra quanto la sessione sta stressando il disco (I/O).

--4.Fase 4: Identificare il codice colpevole: Terminale 2.
--Il DBA sa che c'è un problema di CPU sulla sessione, ma lo sviluppatore ha bisogno di sapere quale codice lo sta causando. 
--Usando il SQL_ID recuperato nella Fase 2 (oppure unendolo direttamente tramite JOIN), andiamo a leggere il testo della query nella V$SQL.

-- Sostituisci &SQL_ID_TROVATO con l'SQL_ID reale, es: '7xqz8a...'
SELECT sql_id, executions, cpu_time, elapsed_time, sql_text
FROM v$sql
WHERE sql_id = '&SQL_ID_TROVATO';

--Cosa notare:
--•	EXECUTIONS: Mostrerà un numero altissimo, spiegando perché la CPU è satura (la query viene lanciata migliaia di volte).
--•	SQL_TEXT: Rivelerà il testo della query colpevole (SELECT COUNT(importo)...).  siamo partiti dal sintomo (server lento) e siamo arrivati alla riga di codice esatta.

