-- LAB 2: Waits Events
--Il modo migliore per spiegare gli eventi di attesa (Wait Events) è creare una situazione in cui il database si "congela" per un motivo logico e non per un sovraccarico hardware. 
--Il classico problema del Row Lock Contention (conflitto di blocco su una riga)
--Per questo laboratorio serviranno tre connessioni (due per simulare le applicazioni concorrenti e uno per il DBA che investiga).

--1.Fase 1: Acquisire il blocco (Senza rilasciarlo): connessione 1.
--Dal primo terminale, si esegue un aggiornamento su una singola riga della tabella ordini, ma omette volutamente il COMMIT.
--Modifichiamo l'importo dell'ordine ID 1, ma non facciamo commit

UPDATE tuning_user.ordini SET importo = 9999 WHERE id_ordine = 1;
--Cosa notare: In questo momento, la transazione ha acquisito un blocco esclusivo (TX lock) su quella specifica riga.
--Nessun altro può modificarla finché la transazione non termina.

--2.Fase 2: Generare l'attesa (Wait Event):connessione 2.
--Dal secondo terminale (sempre come tuning_user), simuliamo un'altra parte dell'applicazione che cerca di aggiornare esattamente la stessa riga.
-- Cerchiamo di aggiornare la stessa riga
UPDATE tuning_user.ordini SET importo = 500 WHERE id_ordine = 1;
--Risultato: Il terminale si blocca. La query rimane in attesa (hanging) e non restituisce il prompt. Il Wait Event è stato generato.

--3.Fase 3: Indagine in Real-Time con le Wait Events: connessione 3 (DBA).
--Ora entriamo in azione con il terminale diagnostico (connesso come SYS o tuning_user). 
--Invece di guardare chi consuma CPU, cerchiamo chi sta aspettando qualcosa interrogando la V$SESSION.

SELECT sid, username, sql_id, event, state, wait_time_micro / 1000000 AS secondi_attesa
FROM v$session
WHERE status = 'ACTIVE' 
AND type != 'BACKGROUND';

--Cosa notare:
--•	La colonna EVENT mostrerà la voce enq: TX - row lock contention. È la prova inequivocabile che il rallentamento non è dovuto a mancanza di CPU o RAM, ma a un blocco logico dei dati.
--•	La colonna STATE sarà su WAITING.
--•	I secondi_attesa continueranno a crescere.

--4.Fase 4: Identificare il colpevole (Blocking Session):Terminale 3 (DBA).
--Abbiamo trovato la "vittima" che sta aspettando, ma chi è il "carnefice" che tiene bloccata la riga? Oracle lo espone direttamente nelle colonne di blocco della V$SESSION.
SELECT 
    s1.sid AS sessione_bloccata,
    s1.event AS motivo_attesa,
    s1.blocking_session AS colpevole_sid,
    s2.username AS colpevole_user,
    s2.status AS colpevole_stato
FROM v$session s1
JOIN v$session s2 ON s1.blocking_session = s2.sid
WHERE s1.blocking_session IS NOT NULL;

--Il SID (quello del Terminale 1) sta paralizzando il lavoro del Terminale 2. 
--Spesso lo stato del colpevole sarà INACTIVE, perché ha lanciato la query, ma si è "dimenticato" di chiudere la transazione con un commit o un rollback.

--5.Fase 5: Analisi Storica con ASH (Active Session History):Terminale 3 (DBA).
--Sul Terminale 1 eseguire una COMMIT;. Il Terminale 2 si sbloccherà istantaneamente.
--Ora interroga di nuovo la V$SESSION: il blocco è sparito e la vista è pulita. 
--Come fa un DBA a dimostrare che c'è stato un problema 5 minuti fa? Entra in gioco la V$ACTIVE_SESSION_HISTORY.

SELECT sample_time, session_id, blocking_session, event, sql_id
FROM v$active_session_history
WHERE event = 'enq: TX - row lock contention'
ORDER BY sample_time DESC
FETCH FIRST 5 ROWS ONLY;

--Cosa notare:
--•	ASH è la "scatola nera" di Oracle. Fotografa le Wait Events attive ogni secondo e le storicizza.
--•	Anche se l'incidente è risolto, ASH permette di estrarre il SQL_ID della query bloccata, a che ora esatta è successo e chi l'ha bloccata, permettendo l'analisi post-mortem (fondamentale per i problemi transitori).


